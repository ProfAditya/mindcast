/**
 * Exploratory reflection modules — question bank.
 *
 * These are NEURIX self-reflection questionnaires, NOT validated clinical instruments. They were written for this product
 * and have not been psychometrically validated. Every result screen says so.
 *
 * Compact item syntax (parsed in ./engine.ts):
 *   L5|text            5-point agree scale, agreement is favourable
 *   L5R|text           5-point agree scale, agreement is unfavourable (reverse-scored)
 *   L7|text / L7R|text 7-point agree scale
 *   F|text / FR|text   frequency (Never … Always); FR = frequent is unfavourable
 *   S|text|a=1;b=0.5   single choice; number after '=' is the item score 0–1
 *   SC|text|…          scenario (single choice describing a situation)
 *   M|text|…           multiple choice; score = sum of chosen option scores, capped at 1
 *   T|text             free text, optional, never scored
 * An item may end with  >>follow-up  : shown only when the answer scores ≤ 0.25. Text ending in '?' is an optional free-text
 * follow-up question; any other text is shown as an information note.
 *
 * Each domain lists 10 items in order: items 1–6 are used in the 30-question version, 7–8 are added for 40, 9–10 for 50.
 * Changing wording, order or scoring REQUIRES bumping the module version.
 */

